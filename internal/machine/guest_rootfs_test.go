func TestWithHostsEntries(t *testing.T) {
	localhost := "127.0.0.1 localhost\n::1 localhost ip6-localhost ip6-loopback\n"
	for _, tc := range []struct {
		name, hosts, hostname, want string
	}{
		{"empty", "", "dev", localhost + "127.0.1.1 dev\n"},
		{"without hostname", "", "", localhost},
		{"existing localhost", "127.0.0.1 localhost\n::1       localhost ip6-localhost ip6-loopback\n", "dev",
			"127.0.0.1 localhost\n::1       localhost ip6-localhost ip6-loopback\n127.0.1.1 dev\n"},
		{"complete", "127.0.0.1 localhost dev\n", "dev", "127.0.0.1 localhost dev\n"},
		{"names only in comments", "# localhost dev\n10.0.0.5 db", "dev", "# localhost dev\n10.0.0.5 db\n" + localhost + "127.0.1.1 dev\n"},
	} {
		if got := withHostsEntries(tc.hosts, tc.hostname); got != tc.want {
			t.Errorf("%s: withHostsEntries = %q, want %q", tc.name, got, tc.want)
		}
	}
}

func TestWriteGuestNameConfigFillsDockerPlaceholders(t *testing.T) {
	guestDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(guestDir, "etc"), 0755); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"hosts", "hostname", "resolv.conf"} {
		if err := os.WriteFile(filepath.Join(guestDir, "etc", name), nil, 0755); err != nil {
			t.Fatal(err)
		}
	}
	root, err := os.OpenRoot(guestDir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()

	for range 2 {
		if err := writeGuestNameConfig(root, "devbox-ubuntu", []string{"172.16.1.249"}); err != nil {
			t.Fatal(err)
		}
	}

	for name, want := range map[string]string{
		"hosts":       "127.0.0.1 localhost\n::1 localhost ip6-localhost ip6-loopback\n127.0.1.1 devbox-ubuntu\n",
		"hostname":    "devbox-ubuntu\n",
		"resolv.conf": "# Generated by kiln-vm.\nnameserver 172.16.1.249\n",
	} {
		got, err := os.ReadFile(filepath.Join(guestDir, "etc", name))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != want {
			t.Errorf("/etc/%s = %q, want %q", name, got, want)
		}
	}
}


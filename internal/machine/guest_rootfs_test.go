func TestWriteGuestFileStaysInsideGuest(t *testing.T) {
	dir := t.TempDir()
	hostDir := filepath.Join(dir, "host")
	hostFile := filepath.Join(hostDir, "target")
	guestDir := filepath.Join(dir, "guest")
	for _, path := range []string{hostDir, filepath.Join(guestDir, "etc")} {
		if err := os.MkdirAll(path, 0755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(hostFile, []byte("host"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(hostFile, filepath.Join(guestDir, "etc", "absolute")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("../../host/target", filepath.Join(guestDir, "etc", "relative")); err != nil {
		t.Fatal(err)
	}
	if err := syscall.Mkfifo(filepath.Join(guestDir, "etc", "fifo"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(hostDir, filepath.Join(guestDir, "escape")); err != nil {
		t.Fatal(err)
	}

	root, err := os.OpenRoot(guestDir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()

	for _, name := range []string{"etc/absolute", "etc/relative", "etc/fifo", "etc/new"} {
		if err := writeGuestFile(root, name, []byte("guest\n"), 0644); err != nil {
			t.Fatalf("writeGuestFile(%s): %v", name, err)
		}
		info, err := os.Lstat(filepath.Join(guestDir, name))
		if err != nil {
			t.Fatal(err)
		}
		if !info.Mode().IsRegular() {
			t.Fatalf("%s mode = %s, want regular file", name, info.Mode())
		}
		got, err := os.ReadFile(filepath.Join(guestDir, name))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != "guest\n" {
			t.Fatalf("%s = %q, want %q", name, got, "guest\n")
		}
	}
	if err := writeGuestFile(root, "escape/target", []byte("guest\n"), 0644); err == nil {
		t.Fatal("writeGuestFile followed a directory symlink out of the guest")
	}
	if got, err := os.ReadFile(hostFile); err != nil || string(got) != "host" {
		t.Fatalf("host file = %q, %v; want unchanged", got, err)
	}
}

